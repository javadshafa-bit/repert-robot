<?php

namespace App\Support\Sms;

/**
 * ارسال پیامک.
 *
 * رابط عمداً باریک است: فقط کد یک‌بارمصرف. هر چیز دیگری (اطلاع‌رسانی گروهی و
 * غیره) اگر لازم شد متد جدا می‌گیرد، تا پیاده‌سازی‌ها ساده بمانند.
 */
interface SmsSender
{
    /**
     * کد یک‌بارمصرف را به شماره می‌فرستد.
     *
     * هرگز throw نمی‌کند — شکست ارسال یک اتفاق عادی است (اعتبار تمام‌شده،
     * شماره‌ی نامعتبر، قطعی سرویس) و جریان ورود باید بتواند پیام مؤدبانه بدهد.
     */
    public function sendOtp(string $phoneNumber, string $code): bool;

    /** برای نمایش وضعیت در داشبورد */
    public function name(): string;

    /** آیا اعتبار لازم تنظیم شده؟ */
    public function isConfigured(): bool;
}
